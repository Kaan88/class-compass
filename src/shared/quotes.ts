/** FNV-1a 32-bit hash of a string (stable across platforms). */
export function hash32(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/** The quote for a class on a local date (YYYY-MM-DD) in a language. Deterministic. */
export function quoteFor(classId: string, localDate: string, locale: 'en' | 'tr'): string {
  const list = locale === 'tr' ? QUOTES_TR : QUOTES_EN;
  return list[hash32(`${classId}|${localDate}`) % list.length]!;
}
