/**
 * Builds the service worker of the teacher and classroom app (S26b, D-190): `dist/client/app-sw.js`.
 *
 * - The worker's code is `src/client/sw/appWorker.ts` (no imports): its types are stripped with Vite's
 *   own transform and the `export` keywords dropped, so the built worker is a classic script.
 * - In front of it go `CC_BUILD_ID` (a hash of every built file name, which carry content hashes, and
 *   of the worker code: a new build is a new worker, the same build the same worker) and `CC_PRECACHE`
 *   (every script and style the main entry can load, statically or lazily; never the student page's,
 *   the scorer's or the board's own files, never source maps or pictures).
 * - `index.html` (only the main entry) gets `<meta name="cc-build" content="…">`, so the worker keeps
 *   only a page of its own build as the offline shell and the page knows its build.
 *
 * Only `vite build` runs it; in development no worker is registered.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformWithOxc, type Plugin } from 'vite';

export const WORKER_SOURCE = fileURLToPath(new URL('../src/client/sw/appWorker.ts', import.meta.url));
export const WORKER_FILE = 'app-sw.js';
const PLACEHOLDER = '__CC_BUILD_ID__';

interface ChunkLike {
  type: 'chunk';
  fileName: string;
  name: string;
  isEntry: boolean;
  imports: string[];
  dynamicImports: string[];
  viteMetadata?: { importedCss?: Set<string> } | undefined;
}
interface AssetLike {
  type: 'asset';
  fileName: string;
}
type BundleLike = Record<string, ChunkLike | AssetLike>;

/** Every script and style reachable from the entry chunk named `entry` (static and lazy imports). */
export function precacheList(bundle: BundleLike, entry = 'main'): string[] {
  const chunks = new Map<string, ChunkLike>();
  for (const f of Object.values(bundle)) if (f.type === 'chunk') chunks.set(f.fileName, f);
  const start = [...chunks.values()].find((c) => c.isEntry && c.name === entry);
  if (!start) throw new Error(`appWorker: no entry chunk named ${entry}`);
  const seen = new Set<string>();
  const files = new Set<string>();
  const visit = (c: ChunkLike) => {
    if (seen.has(c.fileName)) return;
    seen.add(c.fileName);
    files.add(c.fileName);
    for (const css of c.viteMetadata?.importedCss ?? []) files.add(css);
    for (const next of [...c.imports, ...c.dynamicImports]) {
      const n = chunks.get(next);
      if (n) visit(n);
    }
  };
  visit(start);
  return [...files].filter((f) => !f.endsWith('.map')).sort().map((f) => `/${f}`);
}

/** The build id: every built file name (content-hashed) and the worker code. */
export function buildIdOf(bundle: BundleLike, workerCode: string): string {
  const names = Object.keys(bundle).filter((f) => !f.endsWith('.map')).sort().join('\n');
  return createHash('sha256').update(names).update('\0').update(workerCode).digest('hex').slice(0, 16);
}

/** The worker as a classic script: types stripped, `export` dropped, build id and precache list first. */
export async function workerScript(source: string, build: string, precache: readonly string[]): Promise<string> {
  const { code } = await transformWithOxc(source, 'appWorker.ts', { lang: 'ts' });
  const classic = code.replace(/^export (?=(?:async )?(?:const|function|let|class)\b)/gmu, '').replace(/^export \{[^}]*\};?\s*$/gmu, '');
  return `/* Class Compass app worker, build ${build} (S26b, D-190). Generated by scripts/appWorker.ts. */\nconst CC_BUILD_ID = ${JSON.stringify(build)};\nconst CC_PRECACHE = ${JSON.stringify(precache)};\n${classic}`;
}

export function appWorkerPlugin(): Plugin {
  let outDir = 'dist/client';
  return {
    name: 'cc-app-worker',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
      if (!outDir.startsWith('/') && !/^[A-Za-z]:/u.test(outDir)) outDir = join(config.root, outDir);
    },
    transformIndexHtml: {
      order: 'post',
      handler(html, ctx) {
        if (!ctx.filename.replace(/\\/gu, '/').endsWith('/index.html')) return html;
        return html.replace('</head>', `    <meta name="cc-build" content="${PLACEHOLDER}" />\n  </head>`);
      },
    },
    async writeBundle(_options, bundle) {
      const source = readFileSync(WORKER_SOURCE, 'utf8');
      const files = bundle as unknown as BundleLike;
      const build = buildIdOf(files, source);
      const precache = precacheList(files);
      writeFileSync(join(outDir, WORKER_FILE), await workerScript(source, build, precache));
      const indexPath = join(outDir, 'index.html');
      const html = readFileSync(indexPath, 'utf8');
      if (!html.includes(PLACEHOLDER)) throw new Error('appWorker: index.html has no build id placeholder');
      writeFileSync(indexPath, html.replace(PLACEHOLDER, build));
    },
  };
}
